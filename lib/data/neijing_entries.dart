/// 《人纪·黄帝内经》结构化条目（十维度交叉检索）。
///
/// 设计目的：
/// 1. **原文出处清晰**——每条都带 [NeijingEntry.source]（篇·节）与
///    [NeijingEntry.original]（《内经》原文引文），原文与白话、倪师解读**分字段存放**，
///    不再混作一段，读者一眼可分「经典原文 / 白话译解 / 倪师发挥」。
/// 2. **解析维度可扩展**——除原脏象 / 望诊 / 脉诊外，补入病因病机、经络循行、
///    气血津液、辨证体系、治则治法与方药、典型病证、误治与注意，共十维度；
///    [NeijingEntry.tags] 提供跨维度交叉检索（如「心」「阳气」「六经」）。
///
/// 内容属传统文化参考，非医疗建议。倪师解读中非原文直引处一律标注【推断】。
library;

/// 维度定义（key / 中文名 / 一句话说明）。
