package com.jarvis.app.task

/**
 * 分应用用法知识（借鉴 Mika 的 knowledge/apps/<id>/APP.md）。
 * 每个应用一份简短知识：界面结构 + 容易踩的坑。TaskLoop 每步在前台应用
 * 匹配到包名时，把对应知识追加进给模型的 userText，让模型不用每步现猜。
 *
 * 目前只有微信（com.tencent.mm），先做它是因为微信是用户最常用的跨应用
 * 任务目标，也是最难的（扣留界面树、消息内容看不到）。以后加应用只须
 * 在 KNOWLEDGE 里加一条：包名 -> 知识文本。
 *
 * 微信知识改编自 Mika 的 knowledge/apps/wechat/APP.md（Apache-2.0），
 * 另加 Jarvis 在真机上踩过的微信专属教训（zoom 硬规矩、输入框细）。
 */
object AppKnowledge {

    private val KNOWLEDGE: Map<String, String> = mapOf(
        "com.tencent.mm" to
            "微信（聊天与社交 App）。主结构是聊天列表、通讯录、发现、个人页，" +
            "具体布局随版本、账号状态、字体设置而不同。顶部搜索会同时返回联系人、" +
            "群聊、聊天记录、小程序和公众号，结果按分组显示。\n" +
            "容易混淆：未读标记、置顶、草稿、服务通知和普通消息都在聊天列表里；" +
            "联系人显示名、备注名、群名和头像可能相似，进入会话后标题才是实际对象；" +
            "输入框里有文字只是草稿，发出后会话里才有本人的气泡；群聊里每条消息有发言人；" +
            "公众号内容与个人会话是分开的。\n" +
            "微信专属注意：这个应用会扣留界面树，元素可能不全、消息内容看不到；" +
            "树被扣留时先 zoom 再点是硬规矩（没经过新放大的盲点会被系统拒绝，一个界面一次放大）；" +
            "输入框很细，点之前先 zoom 看清再点；发消息要依次打开应用、找到联系人、" +
            "点开会话、输入消息、点发送，发送完成才能结束。"
    )

    /** 返回给定前台包名的用法知识，没有则返回 null。 */
    fun forPackage(pkg: String): String? = KNOWLEDGE[pkg]
}
